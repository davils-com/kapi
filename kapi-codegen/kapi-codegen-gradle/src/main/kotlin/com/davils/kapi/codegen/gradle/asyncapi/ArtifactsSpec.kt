package com.davils.kapi.codegen.gradle.asyncapi

import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input

/**
 * Which artifacts an AsyncAPI document generates from its WebSocket channels. Models are generated by default; a
 * client or a server needs them.
 *
 * @since 1.0.0
 */
public abstract class ArtifactsSpec {
    /**
     * The models of the messages, for every platform.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val models: Property<Boolean>

    /**
     * A client of every channel on the WebSocket sessions of the client runtime, for every platform.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val client: Property<Boolean>

    /**
     * The handlers and routes of every channel on the WebSocket channels of the Ktor server, for the JVM.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val server: Property<Boolean>

    init {
        models.convention(true)
        client.convention(false)
        server.convention(false)
    }

    internal fun names(): Set<String> {
        val chosen = mapOf("Models" to models, "Client" to client, "Server" to server)
        return chosen.filterValues { isChosen -> isChosen.get() }.keys
    }
}
