package com.davils.kapi.codegen.gradle

import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input

/**
 * Which artifacts a specification generates. Models are generated by default; everything else is chosen.
 *
 * @since 1.0.0
 */
public abstract class ArtifactsSpec {
    /**
     * The models of the schemas, for every platform.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val models: Property<Boolean>

    /**
     * A client per tag on the Ktor client, for every platform.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val client: Property<Boolean>

    /**
     * A service interface and its routes per tag on the Ktor server, for the JVM.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val server: Property<Boolean>

    /**
     * Mock services answering with deterministic samples, for the JVM.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val mocks: Property<Boolean>

    /**
     * Senders of the webhooks and callbacks of the document, for every platform.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val senders: Property<Boolean>

    /**
     * Receivers of the webhooks and callbacks of the document on the Ktor server, for the JVM.
     *
     * @since 1.0.0
     */
    @get:Input
    public abstract val receivers: Property<Boolean>

    init {
        models.convention(true)
        client.convention(false)
        server.convention(false)
        mocks.convention(false)
        senders.convention(false)
        receivers.convention(false)
    }

    internal fun names(): Set<String> {
        val chosen = mapOf(
            "Models" to models,
            "Client" to client,
            "Server" to server,
            "Mocks" to mocks,
            "Senders" to senders,
            "Receivers" to receivers,
        )
        return chosen.filterValues { isChosen -> isChosen.get() }.keys
    }
}
